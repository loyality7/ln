package ink

import (
	"testing"

	"github.com/loyality7/ln/ln/geom"
)

func TestPenFluentDrawing(t *testing.T) {
	dr := NewDrawing(400, 400)
	p := dr.Pen()

	// 1. Box stroke
	p.Rect(10, 10, 390, 390).SetWidth(3).Stroke()

	// 2. Fills and cutouts
	p.Circle(200, 200, 50).Fill()
	p.Circle(200, 200, 20).FillWhite()

	// 3. Dynamic stroke with curvature physics
	p.MoveTo(50, 50).CubicTo(100, 150, 150, 50, 200, 100, 16).StrokeDynamic(DynamicStyle(4))

	// 4. Hatching
	p.Rect(30, 30, 100, 100).Hatch(8, 45, 1)

	// 5. Radial lines
	p.RadialLines(geom.Vector{X: 200, Y: 200}, 80, 150, 12, 42)

	// 6. Halftone grid pattern
	dots := HalftoneGrid(geom.Box{Min: geom.Vector{X: 10, Y: 10}, Max: geom.Vector{X: 100, Y: 100}}, 0.3, 6.0, 45.0)
	dr.Layers[len(dr.Layers)-1].Fills = append(dr.Layers[len(dr.Layers)-1].Fills, dots...)

	// 7. Woven hatching
	woven := WovenHatch(geom.Box{Min: geom.Vector{X: 250, Y: 250}, Max: geom.Vector{X: 350, Y: 350}}, 15.0, 3, 0.8)
	dr.Layers[len(dr.Layers)-1].Lines = append(dr.Layers[len(dr.Layers)-1].Lines, woven...)

	if len(dr.Layers) == 0 {
		t.Fatal("expected layers to be generated by Pen")
	}

	totalLines := 0
	totalFills := 0
	for _, l := range dr.Layers {
		totalLines += len(l.Lines)
		totalFills += len(l.Fills)
	}

	if totalLines == 0 {
		t.Errorf("expected lines to be produced, got 0")
	}
	if totalFills == 0 {
		t.Errorf("expected fills to be produced, got 0")
	}

	img := dr.Image(400, 400)
	if img == nil {
		t.Fatal("dr.Image returned nil")
	}
}
